create table if not exists public.catalogo_equipo (
  id uuid primary key default gen_random_uuid(),
  tipo text not null check (tipo in ('bicis','horquillas','shocks','cubiertas','frenos')),
  nombre text not null,
  clave text not null,
  origen text not null default 'usuario' check (origen in ('base','usuario')),
  creado_por uuid,
  creado timestamptz not null default now(),
  unique (tipo, clave)
);
alter table public.catalogo_equipo enable row level security;

create or replace function public.catalogo_clave(t text) returns text
language sql immutable as $$ select lower(regexp_replace(btrim(coalesce(t,'')), '\s+', ' ', 'g')); $$;

