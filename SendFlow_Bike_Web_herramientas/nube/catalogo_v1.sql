-- Todas las listas, ordenadas
create or replace function public.catalogo_listar() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_object_agg(tipo, nombres), '{}'::jsonb) from (
    select tipo, jsonb_agg(nombre order by clave) nombres from catalogo_equipo group by tipo) x;
$$;

-- Agregar un modelo (si ya está, no hace nada). Hasta 40 por persona por día.
create or replace function public.catalogo_agregar(p_tipo text, p_nombre text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := public.coach_uid(); n text := regexp_replace(btrim(coalesce(p_nombre,'')), '\s+', ' ', 'g'); r catalogo_equipo;
begin
  if u is null then raise exception 'Tenés que iniciar sesión.'; end if;
  if p_tipo not in ('bicis','horquillas','shocks','cubiertas','frenos') then raise exception 'Lista inválida.'; end if;
  if length(n) < 2 or length(n) > 80 or n !~ '[[:alnum:]]' or n ~ '[<>"`\\{};]' or n ~ '[[:cntrl:]]' then raise exception 'Revisá el nombre del modelo: sin < > comillas ni símbolos raros.'; end if;
  select * into r from catalogo_equipo where tipo = p_tipo and clave = public.catalogo_clave(n);
  if found then return jsonb_build_object('ok', true, 'nuevo', false, 'nombre', r.nombre); end if;
  if (select count(*) from catalogo_equipo where creado_por = u and creado > now() - interval '1 day') >= 40 then
    raise exception 'Llegaste al máximo de modelos nuevos por hoy.'; end if;
  insert into catalogo_equipo (tipo, nombre, clave, origen, creado_por) values (p_tipo, n, public.catalogo_clave(n), 'usuario', u);
  return jsonb_build_object('ok', true, 'nuevo', true, 'nombre', n);
end $$;

-- Solo el admin: borrar una entrada (por tipo y nombre)
create or replace function public.catalogo_borrar(p_tipo text, p_nombre text) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from perfiles_usuario where id = public.coach_uid() and es_admin) then
    raise exception 'Solo el administrador puede borrar modelos.' using errcode = '42501'; end if;
  delete from catalogo_equipo where tipo = p_tipo and clave = public.catalogo_clave(p_nombre);
  return jsonb_build_object('ok', true);
end $$;

revoke all on function public.catalogo_listar() from public;
revoke all on function public.catalogo_agregar(text, text) from public;
revoke all on function public.catalogo_borrar(text, text) from public;
grant execute on function public.catalogo_listar() to authenticated;
grant execute on function public.catalogo_agregar(text, text) to authenticated;
grant execute on function public.catalogo_borrar(text, text) to authenticated;
